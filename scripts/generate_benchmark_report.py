#!/usr/bin/env python3
"""Generate docs/BENCHMARKS.md from live benchmark runs."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from mcp_bastion.benchmarks.finops_rbac import run_all_benchmarks  # noqa: E402


def _md_table(headers: list[str], rows: list[list[str]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def render_markdown(report: dict) -> str:
    ob_rows = report["output_budget"]["rows"]
    rbac_rows = report["rbac"]["rows"]
    cache_rows = report["lexical_cache"]["rows"]
    disc = report["discovery_filter"]

    ob_table = _md_table(
        ["Tool response (input tokens)", "Kept in context", "Reduction"],
        [
            [
                f"{r['measured_input_tokens']:,}",
                f"{r['output_tokens_kept']:,}",
                f"**{r['reduction_pct']}%**",
            ]
            for r in ob_rows
        ],
    )

    rbac_table = _md_table(
        ["Role", "Tool", "Result"],
        [[r["role"], r["tool"], r["result"]] for r in rbac_rows],
    )

    cache_table = _md_table(
        ["Case", "Query pattern", "Cache hit", "Jaccard vs cached"],
        [
            [
                r["case"],
                r["query"][:48] + ("…" if len(r["query"]) > 48 else ""),
                "Yes" if r["cache_hit"] else "No",
                str(r.get("jaccard_vs_cached", "-")),
            ]
            for r in cache_rows
        ],
    )

    return f"""# MCP-Bastion benchmarks (RBAC & context reduction)

> Auto-generated by `scripts/generate_benchmark_report.py` - re-run after pillar changes.
>
> **Version:** `{report["benchmark_version"]}` · **Generated:** {report["generated_at"]}  
> **Token counter:** {report["token_counter"]}

## Honest summary

{report["disclaimer"]}

| Feature | What we measured | Headline result |
|---------|------------------|-----------------|
| **RBAC** | Tool-level allow/deny by role | Viewer/admin/nobody matrix **passes** (see below) |
| **Output budget + offload** | Oversized **tool response** text | **Up to ~{ob_rows[0]["reduction_pct"]}%** reduction on 50k-token dumps; **0%** when under budget |
| **Discovery filter** | `tools/list` JSON size (20 → 3 tools) | **~{disc["reduction_pct"]}%** fewer catalog tokens (opt-in) |
| **Lexical cache** | Repeat vs paraphrased tool queries | Exact repeat **hits**; paraphrase **misses** at 0.9 threshold |

<p align="center">
  <img
    src="../images/mcp-bastion-finops-benchmarks.png"
    alt="MCP-Bastion benchmarks: RBAC matrix, output budget reduction up to 99%, discovery filter, lexical cache"
    width="960"
    style="max-width:100%; height:auto;"
  />
</p>

## RBAC (tool-level, opt-in)

Pair with **Agent IAM** or **edge auth** - RBAC reads `context.metadata["role"]` / `["agent"]`; without authenticated identity stamping, roles are self-asserted.

{rbac_table}

- Config: `rbac.enabled: true` + `rbac.permissions` in `bastion.yaml`
- Wildcard `*` grants all tools (admin row above)

## Output budget + session offload (opt-in)

Default benchmark config: `max_output_tokens: 4000`, `min_tokens: 500`, offload **on**.
Full text is stored in-session; the model sees a ~250-token pointer + preview.

{ob_table}

**Not a flat “95% prompt reduction”** - small tool outputs (under budget) are **unchanged (0%)**.

Regenerate: `PYTHONPATH=src python -m pytest tests/test_benchmarks_finops_rbac.py -q`

## Discovery filter (opt-in)

Simulated `{disc["total_tools"]}` tool schemas → allowlist `{disc["allowlisted_tools"]}`:

| Metric | Value |
|--------|-------|
| Full `tools/list` tokens | {disc["tools_list_tokens_full"]:,} |
| Filtered tokens | {disc["tools_list_tokens_filtered"]:,} |
| Reduction | **{disc["reduction_pct"]}%** |

## Lexical similarity cache (opt-in; “semantic cache” in config)

Implementation uses **Jaccard word overlap**, not embeddings - name is historical; see `semantic_cache.py`.

Threshold: **{report["lexical_cache"]["similarity_threshold"]}**

{cache_table}

## Reproduce locally

```bash
pip install -e ".[dev]"
PYTHONPATH=src python -m pytest tests/test_benchmarks_finops_rbac.py -v
PYTHONPATH=src python scripts/generate_benchmark_report.py
```

CI runs the pytest module on every merge; this file is updated when maintainers regenerate the report.
"""


def main() -> int:
    report = run_all_benchmarks()
    out = ROOT / "docs" / "BENCHMARKS.md"
    out.write_text(render_markdown(report), encoding="utf-8")
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
